/** ช่วงเวลาของภาพฉาก: กลางวัน พลบค่ำ (รวมรุ่งสาง ฟ้าสีส้มม่วงแบบเดียวกัน) กลางคืน */
export const TIMES = ['day', 'dusk', 'night'] as const;
export type TimeOfDay = (typeof TIMES)[number];

/**
 * คำบอกเวลาในเนื้อเรื่อง [รูปแบบ, เวลา, อ่อน]
 * - เวลา null = มีคำบอกเวลาอยู่ข้างในแต่ไม่ใช่เวลาตอนนี้: เล่าย้อน (เมื่อคืน เมื่อเช้า) ล่วงหน้า (พรุ่งนี้เช้า ถ้าเช้านี้)
 *   กิจวัตร (ทุกคืน ทุกเช้า) ชื่อกะงาน (กะดึก) และคำอื่น (ดึกดำบรรพ์ ผีเสื้อกลางคืน)
 * - อ่อน = มักเป็นช่วงยาวหรือคำเล่ากว้างๆ (ทั้งคืน คืนที่สาม กลางวัน) ใช้เมื่อไม่มีคำบอกเวลาที่ชัดกว่า
 * - ก่อน/จน/ตั้งแต่ เปลี่ยนความหมาย: ก่อนค่ำ = ยังกลางวัน จนเช้า = ทั้งคืน ตั้งแต่หัวค่ำ = ตอนนี้ดึกแล้ว
 *   ตั้งแต่ก่อนรุ่ง = ตอนนี้สว่างแล้ว
 * ไม่ใช้คำเดี่ยวที่มีความหมายอื่นบ่อย: เย็น (น้ำเย็น ใจเย็น) ทุ่ม (ทุ่มเท) บ่าย (บ่ายหน้า)
 * เที่ยง (เที่ยงธรรม) คืน (คืนเงิน กลับคืน) ดาว (ชื่อเกม)
 */
const CUES: [string, TimeOfDay | null, boolean?][] = [
  ['เมื่อ(?:คืน|ตอนเช้า|เช้า|ตอนเย็น|เย็น|ค่ำ|ตอนบ่าย|บ่าย)', null],
  ['ทุก(?:คืน|เช้า|ค่ำ|เย็น|บ่าย)', null],
  ['กะ(?:ดึก|กลางวัน|กลางคืน)', null],
  ['พรุ่งนี้(?:ตอน)?(?:เช้า|สาย|เที่ยง|บ่าย|เย็น|ค่ำ)', null],
  ['(?:ถ้า|รอ)(?:ให้)?(?:ถึง|จน)?(?:ตอน)?(?:เช้า|สาย|บ่าย|เย็น|ค่ำ|ดึก|รุ่ง)(?:นี้)?', null],
  ['ดึกดำบรรพ์', null],
  ['(?:ผีเสื้อ|นก)กลางคืน', null],
  ['ก่อน(?:ค่ำ|มืด|พลบ|ตะวันตกดิน|ตะวันลับ|อาทิตย์ตก|พระอาทิตย์ตก)', 'day'],
  ['ทั้งวันทั้งคืน', null],
  ['ตั้งแต่(?:ก่อน)?(?:รุ่งเช้า|รุ่งสาง|รุ่ง|เช้ามืด|ไก่ขัน|ฟ้าสาง|เช้า)(?:รุ่งเช้า|เช้า)?', 'day'],
  ['ก่อน(?:รุ่งเช้า|รุ่งสาง|รุ่ง|สว่าง|ฟ้าสาง|ไก่ขัน|เช้า)(?:รุ่งเช้า|เช้า)?', 'night'],
  ['จน(?:ถึง)?(?:รุ่งเช้า|รุ่งสาง|เช้า|สว่าง|รุ่ง|ฟ้าสาง)', 'night'],
  ['ตั้งแต่(?:หัวค่ำ|ตกค่ำ|พลบค่ำ|ค่ำ)', 'night'],
  // กลางคืน
  ['เที่ยงคืน', 'night'],
  ['ค่ำคืน', 'night'],
  ['ค่ำมืด|มืดค่ำ', 'night'],
  ['ยามวิกาล', 'night'],
  ['ดึก', 'night'],
  ['คืน(?:นี้|นั้น|หนึ่ง|เดือนมืด|เดือนดับ|เดือนเพ็ญ)', 'night'],
  ['เช้ามืด', 'night'],
  ['(?:สอง|สาม|สี่|ห้า)ทุ่ม', 'night'],
  ['ทั้งคืน|ค้างคืน|ข้ามคืน|คืนที่', 'night', true],
  ['กลางคืน', 'night', true],
  ['แสงจันทร์|ดวงจันทร์|พระจันทร์', 'night', true],
  // พลบค่ำ และรุ่งสาง
  ['หัวค่ำ|พลบค่ำ|ตกค่ำ|พลบ|ค่ำ', 'dusk'],
  ['โพล้เพล้|สนธยา|อัสดง', 'dusk'],
  ['(?:พระ)?อาทิตย์ตก|ตะวันตกดิน|ตะวันลับ', 'dusk'],
  ['(?:ตอน|ยาม|ตก)เย็น|เย็นย่ำ|เย็น(?:วัน)?(?:นี้|นั้น)', 'dusk'],
  ['หนึ่งทุ่ม', 'dusk'],
  ['รุ่งสาง|ฟ้าสาง|ย่ำรุ่ง|รุ่งอรุณ|ตะวันขึ้น|(?:พระ)?อาทิตย์ขึ้น', 'dusk'],
  // กลางวัน
  ['รุ่งเช้า|เช้า', 'day'],
  ['เที่ยงวัน|(?:ตอน|ยาม)เที่ยง(?!คืน)', 'day'],
  ['(?:ตอน|ยาม|ช่วง)บ่าย|บ่าย(?:วัน)?นั้น|บ่ายแก่|บ่าย(?:โมง|สอง|สาม|สี่)', 'day'],
  ['ตอนสาย|สายๆ', 'day'],
  ['แดดจ้า|แดดจัด|กลางแดด|แดดเที่ยง', 'day'],
  ['กลางวัน|แสงแดด', 'day', true],
];
const CUE_RE = new RegExp(CUES.map(([p]) => `(${p})`).join('|'), 'g');

/**
 * เวลาที่เนื้อเรื่องบอก ไม่นับคำในเครื่องหมายคำพูด (คนในเรื่องพูดถึงเวลาอื่นได้)
 * คำบอกเวลาที่ชัดคำสุดท้ายชนะ เพราะตัวเลือกเกิดตอนท้ายข้อความ
 * ("คืนนั้นไฟไหม้ ... พอรุ่งเช้า ชาวบ้านมาถาม" = กลางวัน) ไม่มีคำที่ชัดจึงใช้คำอ่อนคำสุดท้าย ไม่มีเลยคืน null
 */
export function timeInText(text: string): TimeOfDay | null {
  let strong: TimeOfDay | null = null;
  let weak: TimeOfDay | null = null;
  for (const c of timeCues(text)) {
    if (!c.time) continue;
    if (c.weak) weak = c.time;
    else strong = c.time;
  }
  return strong ?? weak;
}

/** คำในวลีเดียวกันก่อนคำบอกเวลาที่ทำให้มันไม่ใช่เวลาตอนนี้: ล่วงหน้า สมมติ เล่าย้อน กิจวัตร */
const NOT_NOW = ['พรุ่งนี้', 'ถ้า', 'เมื่อวาน', 'ทุกวัน', 'ทุกครั้ง', 'ทุกปี', 'ทุกเดือน'];

/** คำบอกเวลาทุกคำในข้อความตามลำดับ (นอกเครื่องหมายคำพูด) สำหรับ timeInText และการตรวจเนื้อหา */
export function timeCues(text: string): { word: string; at: number; time: TimeOfDay | null; weak: boolean }[] {
  const told = text.replace(/"[^"]*"|“[^”]*”/g, (q) => ' '.repeat(q.length));
  return [...told.matchAll(CUE_RE)].map((m) => {
    const at = m.index ?? 0;
    const [, time, weak] = CUES[m.findIndex((g, k) => k > 0 && g !== undefined) - 1] ?? ['', null];
    // ในวลีเดียวกัน (ตั้งแต่ช่องว่างก่อนหน้า) ถ้ามีคำล่วงหน้า เล่าย้อน หรือกิจวัตร คำนั้นไม่ใช่เวลาตอนนี้
    // ("พรุ่งนี้ฝนจะตกตอนบ่าย" "เขาตายเมื่อวานตอนบ่าย" "ทุกวันเขาตื่นแต่เช้า")
    const clause = told.slice(Math.max(told.lastIndexOf(' ', at), told.lastIndexOf('\n', at)) + 1, at);
    const notNow = NOT_NOW.some((w) => clause.includes(w));
    return { word: m[0], at, time: notNow ? null : time, weak: !!weak };
  });
}

/** เวลาของภาพเหตุการณ์: `time:` ที่ผู้เขียนใส่ → คำบอกเวลาในเนื้อเรื่อง → สุ่มคงที่จาก id (กลางวันบ่อยสุด) */
export function eventTime(ev: { id: string; text: string; time?: TimeOfDay } | undefined, fallbackKey: string): TimeOfDay {
  const told = ev?.time ?? (ev ? timeInText(ev.text) : null);
  if (told) return told;
  const key = ev?.id ?? fallbackKey;
  let h = 0;
  for (let i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) >>> 0;
  const r = h % 10;
  return r < 6 ? 'day' : r < 8 ? 'dusk' : 'night';
}
